import assert from "node:assert/strict";
import { access, readFile } from "node:fs/promises";
const root = new URL("../extension/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("manifest.json", root), "utf8"));
const pkg = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
assert.equal(manifest.version, pkg.version);
assert.equal(manifest.manifest_version, 3);
assert.deepEqual(manifest.permissions, ["scripting", "storage"]);
assert.deepEqual(manifest.host_permissions, ["https://chatgpt.com/*"]);
assert.equal(manifest.action.default_popup, undefined);
const background = await readFile(new URL(manifest.background.service_worker, root), "utf8");
const list = name => JSON.parse(new RegExp(`const ${name} = (\\[[^\\]]*\\]);`).exec(background)[1]);
const hover = list("HOVER");
const picker = list("PICKER");
assert.deepEqual(hover, ["components.js", "hover.js"]);
assert.deepEqual(picker, ["color.js", "capture.js", "outline.js", "vector-source.js", "native-svg.js", "raster.js", "exporter.js", "picker.js"]);
assert.deepEqual(manifest.content_scripts, [{ matches: ["https://chatgpt.com/*"], js: hover, run_at: "document_idle" }]);
const scripts = [...hover, ...picker];
for (const file of scripts) assert.match(await readFile(new URL(file, root), "utf8"), new RegExp(`VERSION = "${pkg.version}"`), `${file} version`);
await Promise.all([manifest.background.service_worker, ...Object.values(manifest.icons), ...scripts].map(file => access(new URL(file, root))));
console.log("Manifest and packaged files checked.");
